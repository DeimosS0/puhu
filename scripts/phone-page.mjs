// Builds the page a phone opens (src/phone-page/) into src-tauri/phone/, which
// src-tauri/src/phone.rs embeds: page.js is main.ts bundled with @noble/ciphers
// (minified IIFE, ES2019 so iOS 15 Safari runs it), page.css and page.html are copied.
// Run after changing anything in src/phone-page: npm run phone-page.

import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src/phone-page");
export const OUT = join(ROOT, "src-tauri/phone");

const BANNER =
  "// Generated by scripts/phone-page.mjs from src/phone-page/main.ts (esbuild: bundled with " +
  "@noble/ciphers, minified IIFE, ES2019). Do not edit: change the source, then npm run phone-page.";

/** The three files as they should be in src-tauri/phone/: { "page.js": text, ... }. */
export async function phonePage() {
  const result = await build({
    entryPoints: [join(SRC, "main.ts")],
    bundle: true,
    format: "iife",
    minify: true,
    target: "es2019",
    write: false,
    banner: { js: BANNER },
    logLevel: "silent",
  });
  return {
    "page.js": result.outputFiles[0].text,
    "page.css": readFileSync(join(SRC, "page.css"), "utf8"),
    "page.html": readFileSync(join(SRC, "page.html"), "utf8"),
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(OUT, { recursive: true });
  for (const [name, text] of Object.entries(await phonePage())) {
    writeFileSync(join(OUT, name), text);
    console.log(`src-tauri/phone/${name}  ${(Buffer.byteLength(text) / 1024).toFixed(1)} KB`);
  }
}
